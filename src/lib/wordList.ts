/** Fast lookup set – built once at module load. */
const guessSet = new Set<string>([
  ...ANSWER_WORDS.map(w => w.toLowerCase()),
  ...VALID_GUESSES.map(w => w.toLowerCase()),
]);

/** Returns true if `word` is an acceptable 5-letter guess. */
export function isValidGuess(word: string): boolean {
  return guessSet.has(word.toLowerCase());
}

/**
 * Deterministically pick the answer for a given day number.
 * Uses a simple but consistent hash so answers stay stable even
 * if more words are added in the future (only index matters).
 */
export function getAnswerForDay(dayNumber: number): string {
  // Simple seeded pseudo-random – Mulberry32
  let t = (dayNumber * 2654435761) >>> 0;
  t = ((t ^ (t >>> 16)) * 2246822507) >>> 0;
  t = ((t ^ (t >>> 13)) * 3266489909) >>> 0;
  t = (t ^ (t >>> 16)) >>> 0;
  const index = t % ANSWER_WORDS.length;
  return ANSWER_WORDS[index].toLowerCase();
}
